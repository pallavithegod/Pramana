/** Copy text without assuming the modern Clipboard API is available.
 *
 * `navigator.clipboard` can be unavailable outside HTTPS/localhost and can be
 * disabled by browser permissions. The selection fallback keeps API buttons
 * usable in LAN-hosted demos and restricted browser sessions.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // A denied permission can still succeed through the fallback below.
  }

  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "fixed";
  textarea.style.left = "-9999px";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.focus();
  textarea.select();

  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    textarea.remove();
  }
}
